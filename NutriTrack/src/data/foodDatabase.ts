// Calorie estimation by keyword
export const estimateCaloriesByName = (name: string): FoodItem | null => {
  const lower = name.toLowerCase();
  const found = FOOD_DATABASE.find(
    (f) =>
      f.name.toLowerCase().includes(lower) ||
      lower.includes(f.name.toLowerCase().split(' ')[0])
  );
  return found || null;
};
